import os

# AI 的名字 / 对方的称呼，全部可通过环境变量覆盖，不填则保持原来的默认值。
AI_NAME = os.environ.get("AI_NAME", "AI")
PARTNER_NAME = os.environ.get("PARTNER_NAME", "User")


def _personalize(template: str) -> str:
    """把模板里的占位符 [AI] / [USER] 替换成 AI_NAME/PARTNER_NAME 环境变量的值。
    模板本身用占位符书写（避免源码里出现任何具体人名），这里做一次性字符串替换，
    不影响模板里其余的 {xxx} format 占位符（.replace 只处理字面文本，跟
    大括号语法完全无关，后续 .format(...) 调用照常生效）。"""
    return template.replace("[AI]", AI_NAME).replace("[USER]", PARTNER_NAME)


